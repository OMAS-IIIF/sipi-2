std::vector<std::uint8_t> srgb_profile(PixelLayout layout, unsigned intent) {
    if (intent > 3 || (layout != PixelLayout::gray && layout != PixelLayout::rgb && layout != PixelLayout::rgba))
        throw std::invalid_argument("Invalid sRGB profile layout or intent");
    auto result = layout == PixelLayout::gray ? std::vector<std::uint8_t>(gray.begin(),gray.end()) :
                                              std::vector<std::uint8_t>(rgb.begin(),rgb.end());
    // PNG and ICC use the same 0..3 rendering-intent values. The template's
    // optional profile ID no longer applies after changing its header: unset it.
    result[64] = result[65] = result[66] = 0;
    result[67] = static_cast<std::uint8_t>(intent);
    std::fill(result.begin()+84,result.begin()+100,0);
    return result;
}
